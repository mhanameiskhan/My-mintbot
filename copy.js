async function runFundGas(ctx, amountStr, chainKey = 'rh') {
  try {
    if (!sponsorWallet) {
      return ctx.reply('❌ No sponsor/funder wallet configured.');
    }
    if (!wallets || wallets.length === 0) {
      return ctx.reply('❌ No minting wallets loaded.');
    }

    const { pool, label } = getChainRpcPool(chainKey);
    const isArc = String(chainKey).toLowerCase() === 'arc';
    const tokenName = isArc ? 'USDC' : 'ETH';

    let amountEth; // native amount to send (ETH or USDC units)
    let usdNote = '';

    try {
      const parsed = parseFundAmount(amountStr, chainKey);

      if (parsed.type === 'usd') {
        if (isArc) {
          // Arc native gas token is USDC ≈ $1
          amountEth = parsed.usd;
          usdNote = ` (≈ $${parsed.usd} USDC)`;
        } else {
          const ethPrice = await getEthPriceUsd();
          amountEth = parsed.usd / ethPrice;
          usdNote = ` ($${parsed.usd} ≈ ${amountEth.toFixed(6)} ETH @ $${ethPrice.toFixed(2)})`;
        }
      } else {
        amountEth = parsed.amount;
      }

      if (!Number.isFinite(amountEth) || amountEth <= 0) throw new Error('bad amount');
    } catch (err) {
      return ctx.reply(
        '❌ Invalid amount.\n\n' +
        'Examples:\n' +
        '• <code>0.002</code> (native)\n' +
        '• <code>$3</code> (dollars)\n' +
        '• <code>3usd</code>\n\n' +
        `Error: ${escapeHtml(err.message)}`,
        { parse_mode: 'HTML' }
      );
    }

    // safety cap for accidental huge USD → ETH conversions
    if (!isArc && amountEth > 0.2) {
      return ctx.reply(
        `❌ Amount too high for safety: <b>${amountEth.toFixed(6)} ETH</b>${usdNote}\n` +
        `Max allowed per wallet: 0.2 ETH. Try a smaller $ amount.`,
        { parse_mode: 'HTML' }
      );
    }

    const amountWei = ethers.parseEther(String(amountEth));
    const totalNeeded = amountWei * BigInt(wallets.length);
    const provider = pool.current();
    const funder = sponsorWallet.signer.connect(provider);

    const balance = await provider.getBalance(sponsorWallet.address);
    if (balance < totalNeeded) {
      return ctx.reply(
        `❌ Funder balance too low on ${label}.\n` +
        `Need at least ~${ethers.formatEther(totalNeeded)} ${tokenName} for transfers (plus gas).\n` +
        `Funder balance: ${ethers.formatEther(balance)} ${tokenName}`
      );
    }

    await ctx.reply(
      `⛽ Sending <b>${Number(amountEth).toFixed(6)}</b> ${tokenName} on <b>${label}</b> to <b>${wallets.length}</b> wallets...${usdNote}\n` +
      `From: <code>${escapeHtml(sponsorWallet.address.slice(0, 12))}...</code>`,
      { parse_mode: 'HTML' }
    );

    const results = [];
    let successCount = 0;

    for (const w of wallets) {
      try {
        const tx = await funder.sendTransaction({
          to: w.address,
          value: amountWei,
        });
        await tx.wait();
        successCount += 1;
        results.push(`✅ ${w.address.slice(0, 10)}... ${amountEth} ${tokenName} | ${tx.hash.slice(0, 12)}...`);
      } catch (err) {
        results.push(`❌ ${w.address.slice(0, 10)}... ${(err.message || 'failed').slice(0, 80)}`);
      }
    }

    await ctx.reply(
      `⛽ <b>Fund Gas result</b> (${label})\n` +
      `Success: <b>${successCount}/${wallets.length}</b>\n\n` +
      results.join('\n'),
      { parse_mode: 'HTML' }
    );
  } catch (err) {
    await ctx.reply(`❌ Fund gas failed: ${err.message}`);
  }
}

const ERC721_ABI = [
  'function ownerOf(uint256 tokenId) view returns (address)',
  'function balanceOf(address owner) view returns (uint256)',
  'function tokenOfOwnerByIndex(address owner, uint256 index) view returns (uint256)',
  'function safeTransferFrom(address from, address to, uint256 tokenId)',
  'function transferFrom(address from, address to, uint256 tokenId)',
];

function parsePriceInput(str) {
  const raw = String(str || '').trim().toLowerCase();
  if (!raw || raw === 'none' || raw === '-') return null;

  const usdMatch =
    raw.match(/^\$\s*([0-9]*\.?[0-9]+)$/) ||
    raw.match(/^([0-9]*\.?[0-9]+)\s*\$$/) ||
    raw.match(/^([0-9]*\.?[0-9]+)\s*usd$/);

  if (usdMatch) {
    const usd = Number(usdMatch[1]);
    if (!Number.isFinite(usd) || usd < 0) throw new Error('bad usd price');
    return { kind: 'usd', value: usd };
  }

  const native = Number(raw);
  if (!Number.isFinite(native) || native < 0) throw new Error('bad price');
  return { kind: 'native', value: native };
}

function offerPriceToNativeAndUsd(offer) {
  if (!offer || typeof offer !== 'object') return null;

  const price = offer.price || offer.current_price || {};
  const currency = String(
    price.currency ||
    price.payment_token?.symbol ||
    offer.payment_token?.symbol ||
    'ETH'
  ).toUpperCase();

  const decimals = Number(
    price.decimals ??
    price.payment_token?.decimals ??
    offer.payment_token?.decimals ??
    18
  );

  // Common OpenSea shapes
  let raw =
    price.value ??
    price.current_price ??
    price.amount ??
    offer.current_price ??
    offer.amount ??
    null;

  // Sometimes nested as { value: { raw/value } }
  if (raw && typeof raw === 'object') {
    raw = raw.raw ?? raw.value ?? raw.amount ?? null;
  }

  // Seaport protocol_data fallback (sum of offer item startAmounts is not ideal;
  // for standard ETH/WETH offers, consideration often holds payment — skip if messy)
  if (raw == null && offer.protocol_data?.parameters) {
    const params = offer.protocol_data.parameters;
    const consideration = params.consideration || [];
    // For an offer, the buyer offers payment tokens in "offer" array
    const offerItems = params.offer || [];
    const paymentItem =
      offerItems.find((i) => String(i.itemType) === '1' || i.itemType === 1) ||
      offerItems[0];
    if (paymentItem?.startAmount) raw = paymentItem.startAmount;
  }

  if (raw == null) return null;

  let native = NaN;
  if (typeof raw === 'string') {
    if (/^\d+$/.test(raw)) {
      // integer wei-like
      try {
        native = Number(ethers.formatUnits(raw, decimals));
      } catch {
        native = Number(raw);
      }
    } else {
      native = Number(raw);
    }
  } else if (typeof raw === 'number') {
    // large number likely wei
    if (raw > 1e10) {
      try {
        native = Number(ethers.formatUnits(BigInt(Math.trunc(raw)), decimals));
      } catch {
        native = raw;
      }
    } else {
      native = raw;
    }
  } else if (typeof raw === 'bigint') {
    native = Number(ethers.formatUnits(raw, decimals));
  }

  if (!Number.isFinite(native) || native < 0) return null;

  const usd =
    price.usd != null ? Number(price.usd) :
    price.value_usd != null ? Number(price.value_usd) :
    offer.price?.usd != null ? Number(offer.price.usd) :
    null;

  return {
    native,
    usd: Number.isFinite(usd) ? usd : null,
    currency,
    raw: String(raw),
  };
}

function openseaChainName(chainKey) {
  const k = String(chainKey || '').toLowerCase();
  if (k === 'eth' || k === 'ethereum') return 'ethereum';
  if (k === 'ink') return 'ink';
  if (k === 'arc') return 'arc';
  return 'robinhood';
}

async function runAcceptOffers(ctx, payload) {
  try {
    const { matches, chainKey, contract, slug } = payload;
    const { pool, label } = getChainRpcPool(chainKey);
    const provider = pool.current();
    const chainName = openseaChainName(chainKey);
    const results = [];

    await ctx.reply(
      `💸 Accepting <b>${matches.length}</b> offer(s) on <b>${label}</b>...\n` +
      `Collection: <code>${escapeHtml(slug)}</code>`,
      { parse_mode: 'HTML' }
    );

    for (const m of matches) {
      try {
        if (!m.orderHash) {
          results.push(`❌ #${m.tokenId} missing order hash`);
          continue;
        }

        // OpenSea fulfillment data for accepting an offer (seller side)
        const body = {
          offer: {
            hash: m.orderHash,
            chain: chainName,
            protocol_address: m.protocolAddress,
          },
          fulfiller: {
            address: m.wallet.address,
          },
          consideration: {
            asset_contract_address: contract,
            token_id: m.tokenId,
          },
        };

        const fulfill = await openseaFetch('/offers/fulfillment_data', {
          method: 'POST',
          body,
        });

        // Response shapes vary; try common paths
        const txData =
          fulfill?.fulfillment_data?.transaction ||
          fulfill?.transaction ||
          fulfill?.actions?.[0]?.transaction ||
          null;

        const to =
          txData?.to ||
          txData?.target ||
          fulfill?.to ||
          m.protocolAddress;
        const data =
          txData?.data ||
          txData?.input_data ||
          txData?.calldata ||
          fulfill?.data;
        const value = BigInt(txData?.value || fulfill?.value || '0');

        if (!to || !data) {
          results.push(
            `❌ ${m.wallet.address.slice(0, 10)}... #${m.tokenId} no fulfillment tx data`
          );
          continue;
        }

        const signer = m.wallet.signer.connect(provider);
        const tx = await signer.sendTransaction({ to, data, value });
        const receipt = await tx.wait();

        if (receipt.status === 1) {
          results.push(
            `✅ ${m.wallet.address.slice(0, 10)}... #${m.tokenId} accepted | ${tx.hash.slice(0, 12)}...`
          );
        } else {
          results.push(`❌ ${m.wallet.address.slice(0, 10)}... #${m.tokenId} reverted`);
        }
      } catch (err) {
        results.push(
          `❌ ${m.wallet?.address?.slice(0, 10) || '?'}... #${m.tokenId} → ${(err.message || 'failed').slice(0, 80)}`
        );
      }
    }

    await ctx.reply(
      `💸 <b>Accept result</b> (${label})\n\n` + results.join('\n'),
      { parse_mode: 'HTML' }
    );
  } catch (err) {
    await ctx.reply(`❌ Accept failed: ${err.message}`);
  }
}

async function runListOffers(ctx, chainKey, contractAddress, minPrice, maxPrice) {
  try {
    if (!wallets || wallets.length === 0) {
      return ctx.reply('❌ No minting wallets loaded.');
    }
    if (!ethers.isAddress(contractAddress)) {
      return ctx.reply('❌ Invalid contract address.');
    }

    const { label, openseaSlug } = getChainRpcPool(chainKey);
    const contractLower = contractAddress.toLowerCase();

    await ctx.reply(
      `🔎 Scanning offers on <b>${label}</b>\n` +
      `Contract: <code>${escapeHtml(contractAddress)}</code>\n` +
      `Wallets: <b>${wallets.length}</b>\n` +
      `Please wait...`,
      { parse_mode: 'HTML' }
    );

    let slug;
    try {
      slug = await resolveCollectionSlug(contractAddress, openseaSlug);
    } catch (err) {
      return ctx.reply(`❌ OpenSea collection lookup failed: ${err.message}`);
    }
    if (!slug) return ctx.reply('❌ No OpenSea collection found for that contract on this chain.');

    let ethUsd = null;
    try { ethUsd = await getEthPriceUsd(); } catch { /* optional */ }

    let ownedCount = 0;
    let offerChecked = 0;
    let offerFound = 0;
    let filteredOut = 0;
    const matches = [];
    const debugOwned = [];

    for (const w of wallets) {
      let tokenIds = [];

      // 1) OpenSea account NFTs
      try {
        let next = null;
        let pages = 0;
        do {
          const path =
            `/chain/${openseaSlug}/account/${w.address}/nfts?limit=50` +
            (next ? `&next=${encodeURIComponent(next)}` : '');
          const data = await openseaFetch(path);
          const nfts = data.nfts || [];
          for (const item of nfts) {
            const c = String(
              item.contract ||
              item.contract_address ||
              item.token_contract ||
              item.collection?.contract ||
              ''
            ).toLowerCase();
            if (c && c !== contractLower) continue;
            // if contract field missing, still try when collection slug matches
            const itemSlug = item.collection || item.collection_slug || '';
            if (!c && itemSlug && String(itemSlug).toLowerCase() !== String(slug).toLowerCase()) continue;
            if (!c && !itemSlug) continue;

            const id = item.identifier ?? item.token_id ?? item.tokenId;
            if (id != null) tokenIds.push(String(id));
          }
          next = data.next || null;
          pages += 1;
        } while (next && pages < 6);
      } catch (err) {
        debugOwned.push(`${w.address.slice(0, 10)}... NFT fetch err: ${(err.message || '').slice(0, 50)}`);
      }

      tokenIds = [...new Set(tokenIds)];
      ownedCount += tokenIds.length;
      if (tokenIds.length > 0) {
        debugOwned.push(`${w.address.slice(0, 10)}... owns ${tokenIds.length} token(s)`);
      }

      for (const tokenId of tokenIds.slice(0, 40)) {
        offerChecked += 1;
        let offer = null;

        // 2) best offer
        try {
          const best = await openseaFetch(
            `/offers/collection/${encodeURIComponent(slug)}/nfts/${encodeURIComponent(tokenId)}/best`
          );
          offer = best?.offer || best;
        } catch {
          // try full offers list
          try {
            const all = await openseaFetch(
              `/offers/collection/${encodeURIComponent(slug)}/nfts/${encodeURIComponent(tokenId)}?limit=5`
            );
            const list = all?.offers || [];
            offer = list[0] || null;
          } catch {
            offer = null;
          }
        }

        if (!offer || offer.status && String(offer.status).toUpperCase() === 'INACTIVE') {
          continue;
        }
        offerFound += 1;

        const parsed = offerPriceToNativeAndUsd(offer);
        if (!parsed) {
          filteredOut += 1;
          const rawPrice = JSON.stringify(offer.price || offer.current_price || {}).slice(0, 120);
          // string-only debug row (not acceptable)
          matches.push({
            line: `⚠️ ${w.address.slice(0, 10)}... #${tokenId} price parse failed: <code>${escapeHtml(rawPrice)}</code>`,
            wallet: null,
            tokenId: String(tokenId),
            orderHash: null,
          });
          continue;
        }

        let usd = parsed.usd;
        if (usd == null && ethUsd && ['ETH', 'WETH'].includes(parsed.currency)) {
          usd = parsed.native * ethUsd;
        }

        let pass = true;
        if (minPrice) {
          if (minPrice.kind === 'usd') {
            if (usd == null || usd < minPrice.value) pass = false;
          } else if (parsed.native < minPrice.value) pass = false;
        }
        if (pass && maxPrice) {
          if (maxPrice.kind === 'usd') {
            if (usd == null || usd > maxPrice.value) pass = false;
          } else if (parsed.native > maxPrice.value) pass = false;
        }

        if (!pass) {
          filteredOut += 1;
          continue;
        }

        const priceTxt =
          usd != null
            ? `${parsed.native.toFixed(5)} ${parsed.currency} (≈ $${usd.toFixed(2)})`
            : `${parsed.native.toFixed(5)} ${parsed.currency}`;

        const orderHash =
          offer.order_hash ||
          offer.orderHash ||
          offer.hash ||
          null;
        const protocolAddress =
          offer.protocol_address ||
          offer.protocolAddress ||
          '0x0000000000000068F116a894984e2DB1123eB395';

        matches.push({
          line: `✅ ${w.address.slice(0, 10)}... #${tokenId} → <b>${priceTxt}</b>`,
          wallet: w,
          tokenId: String(tokenId),
          orderHash,
          protocolAddress,
          priceTxt,
          slug,
        });
      }
    }

    const debug =
      `Slug: <code>${escapeHtml(slug)}</code>\n` +
      `Owned tokens found: <b>${ownedCount}</b>\n` +
      `Offers checked: <b>${offerChecked}</b>\n` +
      `Offers found: <b>${offerFound}</b>\n` +
      `Filtered by price: <b>${filteredOut}</b>\n` +
      (debugOwned.length ? `\n${debugOwned.slice(0, 12).join('\n')}` : '');

    if (matches.length === 0) {
      return ctx.reply(
        `ℹ️ No matching offers.\n\n${debug}\n\n` +
        `Tips:\n` +
        `• Confirm wallets own this collection on OpenSea\n` +
        `• Try min <code>$0</code> and max <code>none</code>`,
        { parse_mode: 'HTML' }
      );
    }

    const lines = matches.map((m) => m.line).slice(0, 40).join('\n');
    const header =
      `📋 <b>Offers</b> (${label})\n` +
      `Collection: <code>${escapeHtml(slug)}</code>\n` +
      `Matches: <b>${matches.length}</b>\n\n`;

    await ctx.reply(header + lines, { parse_mode: 'HTML' });
    await ctx.reply(`🧾 Debug\n${debug}`, { parse_mode: 'HTML' });

    const acceptable = matches.filter((m) => m.wallet && m.orderHash);
    if (acceptable.length === 0) {
      return ctx.reply('No offers can be accepted automatically (missing order hash).');
    }

    pendingAcceptOffers = {
      matches: acceptable,
      chainKey,
      contract: contractAddress,
      slug,
    };

    await ctx.reply(
      `💸 Accept <b>${acceptable.length}</b> offer(s)?\n\n` +
      `Type <code>yes</code> to accept, or <code>no</code> to cancel.`,
      { parse_mode: 'HTML' }
    );
  } catch (err) {
    await ctx.reply(`❌ Offers scan failed: ${err.message}`);
  }
}

async function runCollectNfts(ctx, contractAddress, toAddress, tokenIdList, chainKey = 'rh') {
  try {
    if (!wallets || wallets.length === 0) {
      return ctx.reply('❌ No minting wallets loaded.');
    }
    if (!ethers.isAddress(contractAddress)) {
      return ctx.reply('❌ Invalid NFT contract address.');
    }
    if (!ethers.isAddress(toAddress)) {
      return ctx.reply('❌ Invalid destination wallet address.');
    }

    const { pool, label, openseaSlug } = getChainRpcPool(chainKey);
    const provider = pool.current();
    const results = [];
    const wantAll = String(tokenIdList || '').trim().toLowerCase() === 'all';

    let tokenIds = [];
    if (!wantAll) {
      tokenIds = tokenIdList
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .map((s) => {
          if (!/^\d+$/.test(s)) throw new Error(`Invalid token id: ${s}`);
          return BigInt(s);
        });

      if (tokenIds.length === 0) {
        return ctx.reply('❌ No token IDs provided. Example: 1,2,5  or  all');
      }
    }

    await ctx.reply(
      `📦 Collecting ${wantAll ? '<b>ALL</b> tokens' : `<b>${tokenIds.length}</b> token(s)`} on <b>${label}</b>\n` +
      `Contract: <code>${escapeHtml(contractAddress)}</code>\n` +
      `To: <code>${escapeHtml(toAddress)}</code>\n` +
      `From: <b>${wallets.length}</b> wallets...`,
      { parse_mode: 'HTML' }
    );

    let successCount = 0;
    const successWallets = new Set();

    for (const w of wallets) {
      const signer = w.signer.connect(provider);
      const nft = new ethers.Contract(contractAddress, ERC721_ABI, signer);

      let idsForWallet = tokenIds;
      if (wantAll) {
        idsForWallet = [];
        let listed = false;

        try {
          const balance = await nft.balanceOf(w.address);
          const count = Number(balance);
          if (count > 0) {
            for (let i = 0; i < count; i++) {
              const id = await nft.tokenOfOwnerByIndex(w.address, i);
              idsForWallet.push(id);
            }
          }
          listed = true;
        } catch {
          listed = false;
        }

        if (!listed) {
          try {
            const contractLower = contractAddress.toLowerCase();
            let next = null;
            let pages = 0;

            do {
              const path =
                `/chain/${openseaSlug}/account/${w.address}/nfts?limit=50` +
                (next ? `&next=${encodeURIComponent(next)}` : '');
              const data = await openseaFetch(path);
              const nfts = data.nfts || data.tokens || [];

              for (const item of nfts) {
                const itemContract = (
                  item.contract ||
                  item.contract_address ||
                  item.token_contract ||
                  ''
                ).toLowerCase();
                if (itemContract && itemContract !== contractLower) continue;

                const idRaw = item.identifier ?? item.token_id ?? item.tokenId ?? null;
                if (idRaw === null || idRaw === undefined) continue;
                idsForWallet.push(BigInt(String(idRaw)));
              }

              next = data.next || null;
              pages += 1;
            } while (next && pages < 10);
          } catch (err) {
            results.push(
              `❌ ${w.address.slice(0, 10)}... cannot list tokens → ${(err.message || 'failed').slice(0, 70)}`
            );
            continue;
          }
        }

        if (idsForWallet.length === 0) continue;
      }

      for (const tokenId of idsForWallet) {
        try {
          const owner = (await nft.ownerOf(tokenId)).toLowerCase();
          if (owner !== w.address.toLowerCase()) continue;

          const tx = await nft.safeTransferFrom(w.address, toAddress, tokenId);
          await tx.wait();
          successCount += 1;
          successWallets.add(w.address.toLowerCase());
          results.push(
            `✅ ${w.address.slice(0, 10)}... sent #${tokenId.toString()} | ${tx.hash.slice(0, 12)}...`
          );
        } catch (err) {
          results.push(
            `❌ ${w.address.slice(0, 10)}... #${tokenId.toString()} → ${(err.message || 'failed').slice(0, 70)}`
          );
        }
      }
    }

    if (results.length === 0) {
      return ctx.reply('ℹ️ Nothing to collect (no owned tokens found).');
    }

    await ctx.reply(
      `📦 <b>Collect NFTs result</b> (${label})\n` +
      `Sent <b>${successCount}</b> token(s) from <b>${successWallets.size}</b> wallet(s)\n\n` +
      results.join('\n'),
      { parse_mode: 'HTML' }
    );
  } catch (err) {
    await ctx.reply(`❌ Collect failed: ${err.message}`);
  }
}

