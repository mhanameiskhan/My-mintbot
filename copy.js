// ---------------------------------------------------------------------------
// Small helper: fetch with a hard timeout, so a hung dependency fails
// loud instead of hanging the whole process forever.
// ---------------------------------------------------------------------------

function fetchWithTimeout(url, options = {}, timeoutMs = 10000) {
  const controller = new AbortController();
  const id = setTimeout(() => controller.abort(), timeoutMs);
  return fetch(url, { ...options, signal: controller.signal }).finally(() => clearTimeout(id));
}

// Telegram's legacy "Markdown" parse mode breaks on any unmatched _ * ` [ ] —
// which is very easy to hit by accident (e.g. "DRY_RUN", an error message,
// or an OpenSea slug with an underscore in it). HTML parse mode only cares
// about actual tags, so it's far more robust — but any dynamic text placed
// inside a tag still needs escaping so a literal "<" or "&" doesn't break it.
function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

async function withTimeout(promise, timeoutMs, label) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => reject(new Error(`[timeout] ${label} took longer than ${timeoutMs}ms`)), timeoutMs);
  });
  try {
    return await Promise.race([promise, timeout]);
  } finally {
    clearTimeout(timer);
  }
}

