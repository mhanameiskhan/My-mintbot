/**
 * telegram-mint-bot.js  —  Robinhood Chain
 *
 * Combines watch-and-mint.js's detection + copy-mint pipeline with:
 *   - Telegram notifications: posts when a watched wallet mints, and
 *     again when this bot successfully copies that mint
 *   - Telegram commands to manage the watched-wallet list, backed by
 *     Supabase instead of a static .env value:
 *       /addwallet 0x...      add a wallet to watch
 *       /removewallet 0x...   stop watching a wallet
 *       /wallets              list all watched wallets + how many
 *       /status               show DRY_RUN state and poll interval
 *       /help                 list commands
 *
 * CHANGES IN THIS VERSION (debugging a "silent hang" on startup):
 *   1. Startup checkpoint logs — every await in main() now logs before
 *      and after, so a hang shows you exactly which call never returns
 *      instead of just staring at a blank terminal.
 *   2. Network timeouts everywhere — Supabase client, OpenSea fetch,
 *      Blockscout fetch, and the ethers RPC providers all now have an
 *      explicit timeout (8-12s) instead of Node's default of "forever".
 *      A hung dependency now fails loud instead of hanging silent.
 *   3. Global unhandledRejection / uncaughtException handlers — so a
 *      promise rejection that used to vanish now prints a stack trace.
 *   4. PRIVATE_KEY format validation — previously an empty string or a
 *      malformed key only surfaced as an opaque ethers error deep in
 *      Wallet construction. Now checked up front with a clear message.
 *
 * WHY SUPABASE INSTEAD OF WATCHED_WALLETS IN .env:
 * .env is static — changing it means editing a file and restarting the
 * process. Storing the wallet list in Supabase means /addwallet from
 * Telegram takes effect on the very next poll cycle, no restart needed.
 * The bot re-reads the table from Supabase every WALLET_REFRESH_MS.
 *
 * SUPABASE TABLE (run once in the Supabase SQL editor):
 *   create table watched_wallets (
 *     id bigint generated by default as identity primary key,
 *     address text unique not null,
 *     added_at timestamptz default now()
 *   );
 *
 * MINTING LOGIC — unchanged from watch-and-mint.js:
 *   1. Detect a Transfer(0x0 -> watched wallet) on Robinhood Chain
 *   2. Resolve the contract to an OpenSea collection, mint via the
 *      Drops API (POST /drops/{slug}/mint)
 *   3. If there's no OpenSea Drop for it, fall back to a verified ABI
 *      from Blockscout and a short list of common mint() signatures
 *   See watch-and-mint.js's file header for the full rationale on both.
 *
 * SAFETY DEFAULT: DRY_RUN=true — logs/notifies what WOULD happen without
 * broadcasting any transaction. Flip to false only after confirming
 * detection + Telegram notifications both work correctly.
 *
 * .env required:
 *   TELEGRAM_BOT_TOKEN=...        from @BotFather
 *   TELEGRAM_CHAT_ID=...          chat/group/channel id to post alerts to
 *   SUPABASE_URL=...
 *   SUPABASE_KEY=...              service_role or anon key with table access
 *   RPC_URLS=...                  comma-separated Robinhood Chain RPCs
 *   OPENSEA_API_KEY=...
 *   PRIVATE_KEY=...               required unless DRY_RUN=true
 *   WALLET_ADDRESS=...            your minting wallet — must match PRIVATE_KEY
 *
 * npm i telegraf @supabase/supabase-js ethers dotenv node-fetch
 * node telegram-mint-bot.js
 */

