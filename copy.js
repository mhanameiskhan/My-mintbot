bot.on('text', async (ctx, next) => {
  if (!isAuthorizedChat(ctx)) return next();

  const text = (ctx.message.text || '').trim();

  // Let commands and menu buttons be handled by their own handlers
  if (
    text.startsWith('/') ||
    text.startsWith('⛽') ||
    text.startsWith('📦') ||
    text.startsWith('📊') ||
    text.startsWith('🎯') ||
    text.startsWith('⏸') ||
    text.startsWith('▶️') ||
    text.startsWith('💰') ||
    text.startsWith('💎') ||
    text.startsWith('💜') ||
    text.startsWith('🟧') ||
    text.startsWith('👛') ||
    text.startsWith('ℹ️') ||
    text.startsWith('💸')
  ) {
    return next();
  }

  
  // If no interactive flow is active, do not block other handlers
  if (!pendingFundGas && !pendingCollect && !pendingOffers && !pendingAcceptOffers) {
    return next();
  }

  if (text.toLowerCase() === 'cancel') {
    pendingFundGas = null;
    pendingCollect = null;
    pendingOffers = null;
    pendingAcceptOffers = null;
    return ctx.reply('Cancelled.');
  }

  // Accept offers confirmation
  if (pendingAcceptOffers) {
    const ans = text.toLowerCase();
    if (ans === 'no' || ans === 'n') {
      pendingAcceptOffers = null;
      return ctx.reply('Cancelled offer accept.');
    }
    if (ans === 'yes' || ans === 'y') {
      const payload = pendingAcceptOffers;
      pendingAcceptOffers = null;
      await runAcceptOffers(ctx, payload);
      return;
    }
    return ctx.reply('Type <code>yes</code> to accept or <code>no</code> to cancel.', {
      parse_mode: 'HTML',
    });
  }

  // Fund gas flow: chain → amount
  if (pendingFundGas && typeof pendingFundGas === 'object') {
    if (pendingFundGas.step === 'chain') {
      const chainKey = parseChainKey(text);
      if (!chainKey) {
        return ctx.reply('❌ Invalid chain. Use: rh / eth / ink');
      }
      pendingFundGas = { step: 'amount', chain: chainKey };
      const tokenName = chainKey === 'arc' ? 'USDC' : 'ETH';
      return ctx.reply(
        `⛽ Step 2/2 — Amount for <b>each</b> wallet on <b>${chainKey}</b>.\n\n` +
        `Native ${tokenName}: <code>0.002</code>\n` +
        `Or dollars: <code>$3</code> / <code>3usd</code>`,
        { parse_mode: 'HTML' }
      );
    }

    if (pendingFundGas.step === 'amount') {
      const chainKey = pendingFundGas.chain || 'rh';
      pendingFundGas = null;
      await runFundGas(ctx, text, chainKey);
      return;
    }
  }

    // Offers flow: chain → contract → min → max
  if (pendingOffers) {
    if (pendingOffers.step === 'chain') {
      const chainKey = parseChainKey(text);
      if (!chainKey) return ctx.reply('❌ Invalid chain. Use: rh / eth / ink / arc');
      pendingOffers = { step: 'contract', chain: chainKey };
      return ctx.reply('💸 Step 2/4 — Send the collection <b>contract address</b>.', { parse_mode: 'HTML' });
    }

    if (pendingOffers.step === 'contract') {
      if (!ethers.isAddress(text)) return ctx.reply('❌ Invalid contract address.');
      pendingOffers = { step: 'min', chain: pendingOffers.chain, contract: text };
      return ctx.reply(
        '💸 Step 3/4 — Min price.\nExamples: <code>$20</code> or <code>0.01</code>',
        { parse_mode: 'HTML' }
      );
    }

    if (pendingOffers.step === 'min') {
      try {
        const minPrice = parsePriceInput(text);
        if (!minPrice) return ctx.reply('❌ Min price required.');
        pendingOffers = {
          step: 'max',
          chain: pendingOffers.chain,
          contract: pendingOffers.contract,
          min: minPrice,
        };
        return ctx.reply(
          '💸 Step 4/4 — Max price.\nExamples: <code>$100</code> / <code>0.05</code> / <code>none</code>',
          { parse_mode: 'HTML' }
        );
      } catch {
        return ctx.reply('❌ Invalid min price.');
      }
    }

    if (pendingOffers.step === 'max') {
      try {
        const maxPrice = parsePriceInput(text);
        const { chain, contract, min } = pendingOffers;
        pendingOffers = null;
        await runListOffers(ctx, chain, contract, min, maxPrice);
        return;
      } catch {
        return ctx.reply('❌ Invalid max price. Use a number, $amount, or none.');
      }
    }
  }

  // Collect flow: chain → contract → destination → ids
  if (pendingCollect) {
    if (pendingCollect.step === 'chain') {
      const chainKey = parseChainKey(text);
      if (!chainKey) {
        return ctx.reply('❌ Invalid chain. Use: rh / eth / ink');
      }
      pendingCollect = { step: 'contract', chain: chainKey };
      return ctx.reply(
        '📦 Step 2/4 — Send the NFT <b>contract address</b>.',
        { parse_mode: 'HTML' }
      );
    }

    if (pendingCollect.step === 'contract') {
      if (!ethers.isAddress(text)) {
        return ctx.reply('❌ Invalid contract address. Try again, or type cancel.');
      }
      pendingCollect = {
        step: 'destination',
        chain: pendingCollect.chain,
        contract: text,
      };
      return ctx.reply(
        '📦 Step 3/4 — Send the <b>destination wallet address</b>.',
        { parse_mode: 'HTML' }
      );
    }

    if (pendingCollect.step === 'destination') {
      if (!ethers.isAddress(text)) {
        return ctx.reply('❌ Invalid destination address. Try again, or type cancel.');
      }
      pendingCollect = {
        step: 'ids',
        chain: pendingCollect.chain,
        contract: pendingCollect.contract,
        to: text,
      };
      return ctx.reply(
        '📦 Step 4/4 — Token IDs:\n<code>1,2,5</code> or <code>all</code>',
        { parse_mode: 'HTML' }
      );
    }

    if (pendingCollect.step === 'ids') {
      const chainKey = pendingCollect.chain || 'rh';
      const contract = pendingCollect.contract;
      const to = pendingCollect.to;
      pendingCollect = null;
      await runCollectNfts(ctx, contract, to, text, chainKey);
      return;
    }
  }

  return next();
});

